/**
 * Exports the deterministic 9:16 fixture set and the vertical card feed.
 *
 *   node scripts/vertical-video-feed-fixtures.mjs                      # summary
 *   node scripts/vertical-video-feed-fixtures.mjs --format json        # classification cases
 *   node scripts/vertical-video-feed-fixtures.mjs --format markdown    # reviewable table
 *   node scripts/vertical-video-feed-fixtures.mjs --feed 50            # 50 vertical cards
 *   node scripts/vertical-video-feed-fixtures.mjs --feed 50 --playback-ids id1,id2
 *   node scripts/vertical-video-feed-fixtures.mjs --format json --out /tmp/f.json
 *
 * Two audiences:
 *
 *   - The data lane, which needs the classification cases as JSON to seed a
 *     deployment or to assert its Convex classifier against.
 *   - A reviewer, who needs the same cases as a table with the intent spelled
 *     out next to each one.
 *
 * The command re-derives every expectation from the oracle before printing and
 * exits non-zero if any fixture disagrees, so an export can never publish a
 * table the code does not actually produce.
 *
 * `--feed` output carries `synthetic-not-playable-` playback IDs unless real
 * ones are supplied. Those will not resolve against Mux: a scroll or memory
 * scenario needs `--playback-ids` pointing at real exact-9:16 assets.
 */

import { writeFileSync } from "node:fs";

import { loadVerticalLib } from "./vertical-video-feed-load-lib.mjs";

const lib = await loadVerticalLib();
const fixtures = lib["vertical-video-feed-fixtures"];

const argv = globalThis.process.argv.slice(2);

function flagValue(name) {
  const index = argv.indexOf(name);
  return index !== -1 ? argv[index + 1] : null;
}

const format = flagValue("--format") ?? "summary";
const feedCount = flagValue("--feed");
const playbackIdsRaw = flagValue("--playback-ids");
const outPath = flagValue("--out");

const disagreements = fixtures.findFixtureOracleDisagreements();
if (disagreements.length > 0) {
  globalThis.console.error(
    "Fixture expectations disagree with the oracle; refusing to export:\n" +
      disagreements
        .map((entry) => `  ${entry.fixtureId}.${entry.field}: expected ${entry.expected}, got ${entry.actual}`)
        .join("\n"),
  );
  globalThis.process.exit(1);
}

function describe(fixture) {
  const classification = fixtures.classifyFixture(fixture);
  const visibility = fixtures.evaluateFixtureVisibility(fixture);

  return {
    id: fixture.id,
    group: fixture.group,
    intent: fixture.intent,
    sourceAspectRatio: fixture.sourceAspectRatio ?? null,
    status: fixture.status,
    isReady: fixture.isReady,
    isDeleted: fixture.isDeleted,
    playbackIds: fixture.playbackIds,
    feedVisible: fixture.feedVisible,
    normalizedAspectRatio: classification.aspectRatio,
    feedPlacement: classification.feedPlacement,
    unknownReason: classification.unknownReason,
    eligibleForShorts: visibility.eligible,
    ineligibilityReasons: visibility.reasons,
  };
}

function renderSourceCell(value) {
  if (value === undefined) return "_absent_";
  if (value === null) return "`null`";
  if (typeof value !== "string") return `\`${JSON.stringify(value)}\` (${typeof value})`;
  if (value === "") return "`\"\"`";
  // Backticks preserve leading and trailing spaces that markdown would eat.
  return `\`${value.replace(/ /g, "·")}\``;
}

function renderMarkdown(rows) {
  const lines = [
    "# 9:16 vertical feed fixture set",
    "",
    "Generated by `scripts/vertical-video-feed-fixtures.mjs --format markdown`.",
    "Source values render spaces as `·` so padded input is visible.",
    "",
    "| Fixture | Group | Source `aspect_ratio` | Normalized | Placement | Eligible | Why |",
    "| --- | --- | --- | --- | --- | :---: | --- |",
  ];

  for (const row of rows) {
    const why =
      row.ineligibilityReasons.length > 0
        ? row.ineligibilityReasons.join(", ")
        : row.intent;
    lines.push(
      `| \`${row.id}\` | ${row.group} | ${renderSourceCell(row.sourceAspectRatio)} | ` +
        `${row.normalizedAspectRatio ? `\`${row.normalizedAspectRatio}\`` : "—"} | ` +
        `${row.feedPlacement} | ${row.eligibleForShorts ? "yes" : "no"} | ${why} |`,
    );
  }

  return lines.join("\n");
}

function renderSummary(rows) {
  const byGroup = new Map();
  for (const row of rows) {
    byGroup.set(row.group, (byGroup.get(row.group) ?? 0) + 1);
  }

  const lines = [
    `Fixtures: ${rows.length}`,
    `Eligible for Shorts: ${rows.filter((row) => row.eligibleForShorts).length}`,
    `Never eligible:      ${rows.filter((row) => !row.eligibleForShorts).length}`,
    "",
    "By group:",
  ];
  for (const [group, count] of [...byGroup].sort()) {
    lines.push(`  ${group.padEnd(22)} ${count}`);
  }

  lines.push("", "Oracle agreement: every fixture matches its recorded expectation.");
  return lines.join("\n");
}

let output;

if (feedCount !== null) {
  const count = Number.parseInt(feedCount, 10);
  if (!Number.isInteger(count) || count <= 0) {
    globalThis.console.error(`--feed expects a positive integer, received "${feedCount}"`);
    globalThis.process.exit(1);
  }

  const playbackIds = playbackIdsRaw
    ? playbackIdsRaw.split(",").map((id) => id.trim()).filter(Boolean)
    : undefined;

  const feed = fixtures.createDeterministicVerticalFeed({ count, playbackIds });
  output = JSON.stringify(feed, null, 2);

  if (!playbackIds) {
    globalThis.console.error(
      "Note: no --playback-ids supplied, so these cards carry synthetic IDs that will not resolve against Mux.",
    );
  }
} else {
  const rows = fixtures.VERTICAL_FEED_FIXTURES.map(describe);
  output =
    format === "json"
      ? JSON.stringify(rows, null, 2)
      : format === "markdown"
        ? renderMarkdown(rows)
        : renderSummary(rows);
}

if (outPath) {
  writeFileSync(outPath, `${output}\n`, "utf8");
  globalThis.console.log(`Wrote ${outPath}`);
} else {
  globalThis.console.log(output);
}
